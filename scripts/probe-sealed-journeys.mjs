// J10: Settings theme persists across a packaged relaunch
// ---------------------------------------------------------------------------

export async function probeThemePersistsAcrossRelaunch({
  page,
  relaunch,
  output,
}) {
  const mod = process.platform === "darwin" ? "Meta" : "Control";
  const before = await page.evaluate(() => {
    const raw = window.localStorage.getItem("drogon:settings:ui");
    const theme = raw
      ? (JSON.parse(raw).settings?.theme ?? "system")
      : "system";
    return {
      theme,
      dark: document.documentElement.classList.contains("dark"),
    };
  });
  // Flip the persisted choice so the relaunch has something to prove.
  const target = before.theme === "dark" ? "light" : "dark";
  await focusChrome(page);
  await page.keyboard.press(`${mod}+,`);
  const settings = page.locator('section[aria-label="Settings"]');
  await settings.waitFor();
  await page.getByRole("button", { name: "Appearance", exact: true }).click();
  const themeGroup = page.getByRole("radiogroup", { name: "Theme", exact: true });
  await themeGroup.waitFor();
  // Segmented radios expose their label text as the accessible name.
  const themeLabel = target.charAt(0).toUpperCase() + target.slice(1);
  await themeGroup.getByRole("radio", { name: themeLabel, exact: true }).click();
  await page.waitForFunction(
    (wanted) => document.documentElement.classList.contains("dark") === wanted,
    target === "dark",
    { timeout: 10000 },
  );
  await shot(page, output, `settings-theme-${target}.png`);
  await delay(2000); // the settings store debounces its save
  page = await relaunch();
  await page.waitForFunction(
    (wanted) => document.documentElement.classList.contains("dark") === wanted,
    target === "dark",
    { timeout: 30000 },
  );
  const persisted = await page.evaluate(() => {
    const raw = window.localStorage.getItem("drogon:settings:ui");
    return raw ? (JSON.parse(raw).settings?.theme ?? "system") : "system";
  });
  assert.equal(persisted, target);
  await shot(page, output, `theme-persists-relaunch-${target}.png`);
  // Restore the prior choice so the run's remaining captures (and the
  // sealed screenshots) keep their original scheme.
  await focusChrome(page);
  await page.keyboard.press(`${mod}+,`);
  const settingsAfterRelaunch = page.locator(
    'section[aria-label="Settings"]',
  );
  await settingsAfterRelaunch.waitFor();
  await page.getByRole("button", { name: "Appearance", exact: true }).click();
  const restoreLabel =
    before.theme.charAt(0).toUpperCase() + before.theme.slice(1);
  await page
    .getByRole("radiogroup", { name: "Theme", exact: true })
    .getByRole("radio", { name: restoreLabel, exact: true })
    .click();
  await delay(2000);
  // Leave the app on the session strip so the probes that follow the
  // journey block (restart, stub) find their usual surface.
  await page.keyboard.press("Escape").catch(() => {});
  await page
    .getByRole("button", { name: "Back to app", exact: true })
    .click()
    .catch(() => {});
  await page
    .getByRole("button", { name: "New tab", exact: true })
    .waitFor({ timeout: 30000 });
  return [`settings-theme-${target}-persists-across-packaged-relaunch`];
}
