/** Classifies a fake-gh argv so the fixture answers exactly one shape. */
export function classifyGhArgv(argv) {
  const joined = argv.join(" ");
  if (/\bissue\b/.test(joined) && /\blist\b/.test(joined)) return "issue-list";
  if (/\bissue\b/.test(joined) && /\bview\b/.test(joined)) return "issue-view";
  if (/\bapi\b/.test(joined) && /\buser\b/.test(joined)) return "api-user";
  return "other";
}

/** One fixture issue in the exact `gh issue list --json` field shape. */
export function fixtureIssueJson(number, title, extra = {}) {
  return {
    number,
    title,
    state: "OPEN",
    labels: [],
    assignees: [],
    author: { login: "drogon-acceptance" },
    updatedAt: "2026-09-08T00:00:00Z",
    url: `https://github.com/drogon-fixture/no-such-repo-acceptance/issues/${number}`,
    ...extra,
  };
}

/**
 * Deterministic `gh` fixture (pure POSIX sh, no node on the daemon PATH):
 * `issue list` honors --limit so the daemon's fetch-one-extra hasNextPage
 * probe stays truthful; `issue view N` answers the matching issue; `api
 * user` resolves @me for filter queries. Anything else exits 2 so a stray
 * gh call fails the run honestly instead of silently passing.
 */
export function fixtureGhScript({ issues }) {
  const compact = (value) => JSON.stringify(value);
  const listCases = issues
    .map((issue, index) => {
      const window = issues.slice(0, index + 1);
      return `      ${index + 1}) printf '%s\\n' '${compact(window)}' ;;`;
    })
    .join("\n");
  const viewCases = issues
    .map(
      (issue) =>
        `    *"issue view ${issue.number} "* ) printf '%s\\n' '${compact(fixtureIssueJson(issue.number, issue.title, { body: `Fixture body for issue ${issue.number}.` }))}' ;;`,
    )
    .join("\n");
  return `#!/bin/sh
# Deterministic gh fixture for the sealed Tasks journey (R16-BB): serves a
# fixed issue list/view from argv only, never the network. Generated by
# scripts/probe-sealed-journeys.mjs.
joined="\$*"
limit=""
prev=""
for arg in "\$@"; do
  if [ "\$prev" = "--limit" ]; then limit="\$arg"; fi
  prev="\$arg"
done
case "\$joined" in
  *"issue list"*)
    case "\$joined" in
      *"--state open"*) : ;;
      *) echo "fixture gh only serves open issues: \$joined" >&2; exit 2 ;;
    esac
    case "\$limit" in
${listCases}
      *) printf '%s\\n' '${compact(issues.map((issue) => fixtureIssueJson(issue.number, issue.title)))}' ;;
    esac
    ;;
${viewCases}
    *"issue view "* )
      echo "fixture gh: unknown issue view argv: \$joined" >&2; exit 2 ;;
  "api user")
    printf '%s\\n' '{"login":"drogon-acceptance"}'
    ;;
  *)
    echo "fixture gh: unhandled argv: \$joined" >&2; exit 2 ;;
esac
exit 0
`;
}

