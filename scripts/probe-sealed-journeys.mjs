async function prepareJourneyTasksRepo() {
  const repo = await mkdtemp(path.join(tmpdir(), "drogon-journey-tasks-"));
  const identity = [
    "-c",
    "user.email=acceptance@drogon.local",
    "-c",
    "user.name=Drogon Acceptance",
    "-c",
    "init.defaultBranch=main",
  ];
  await runAcceptanceProcess("git", [...identity, "init"], { cwd: repo });
  await writeFile(path.join(repo, "notes.txt"), "journey fixture\n");
  await runAcceptanceProcess("git", [...identity, "add", "notes.txt"], { cwd: repo });
  await runAcceptanceProcess("git", [...identity, "commit", "-m", "fixture"], { cwd: repo });
  await runAcceptanceProcess(
    "git",
    [...identity, "remote", "add", "origin", "https://github.com/drogon-fixture/journey-acceptance.git"],
    { cwd: repo },
  );
  return repo;
}

export async function probeTasksStartIssue({ page, cli, dataDir, output }) {
  // Self-contained: own repo + project (the gh fixture on the daemon PATH
  // serves two open issues for any repo), removed again in the cleanup.
  const repo = await prepareJourneyTasksRepo();
  const added = await runCliJson(
    cli,
    ["--data-dir", dataDir, "--json", "project", "add", repo, "--name", "acceptance-issues"],
    { timeout: 30000 },
  );
  assert.equal(added.ok, true, JSON.stringify(added.error ?? added));
  const projectId = added.result.project?.id ?? added.result.id;
  assert.ok(projectId);
  // The task picker reads the project view the App loaded at refresh, so
  // reload after the CLI-side add — the same path the surfaces probe uses.
  await page.reload();
  await page
    .getByRole("button", { name: "Reveal active workspace", exact: true })
    .waitFor();
  await page.getByRole("button", { name: "Tasks", exact: true }).click();
  const tasksList = page.locator('[data-testid="tasks-page-host"]');
  await tasksList.waitFor();
  const projectSelect = tasksList.getByRole("combobox", { name: "Project", exact: true });
  await projectSelect.waitFor({ timeout: 30000 });
  await projectSelect.selectOption({ label: "acceptance-issues" });
  const issueRow = tasksList.getByRole("button", { name: "Issue #1" });
  await issueRow.waitFor({ timeout: 60000 });
  await shot(page, output, "tasks-issues-listed.png");
  await tasksList
    .getByRole("button", { name: "Start workspace from issue", exact: true })
    .first()
    .click();
  // The sidebar gains a card for the new worktree, badged with the issue
  // number, and the daemon records the task link. The sidebar loads from
  // its last fetch, so nudge Refresh like a user watching for the card.
  await page
    .getByRole("button", { name: "Refresh connection", exact: true })
    .click()
    .catch(() => {});
  const badge = page.locator(".shell-worktree-card-issue", { hasText: "#1" });
  await badge.waitFor({ timeout: 60000 });
  assert.equal(await badge.getAttribute("title"), "Started from issue #1");
  await shot(page, output, "tasks-start-issue-badge.png");
  const worktrees = await runCliJson(
    cli,
    ["--data-dir", dataDir, "--json", "worktree", "list", "--project", projectId],
    { timeout: 30000 },
  );
  assert.equal(worktrees.ok, true);
  const linked = worktrees.result.worktrees.find((entry) =>
    /issue-1-/.test(entry.branch ?? ""),
  );
  assert.ok(linked, "tasks.start must create the issue-N-<slug> worktree");
  try {
    // Stop the shell that `tasks.start` created before removing its
    // workspace. Otherwise the durable session becomes orphaned from
    // workspace.list and blocks the packaged fixture's quiescent shutdown.
    await stopWorkspaceSessions(cli, dataDir, linked.workspaceId);
    // Cleanup: remove the worktree (and its card) and the project —
    // nothing the journey created may outlive it.
    const removed = await runCliJson(
      cli,
      ["--data-dir", dataDir, "--json", "worktree", "rm", linked.id, "--force"],
      { timeout: 30000 },
    );
    assert.equal(removed.ok, true, JSON.stringify(removed.error ?? removed));
    const projectRemoved = await runCliJson(
      cli,
      ["--data-dir", dataDir, "--json", "project", "remove", projectId],
      { timeout: 30000 },
    );
    assert.equal(projectRemoved.ok, true, JSON.stringify(projectRemoved.error ?? projectRemoved));
    await page
      .getByRole("button", { name: "Refresh connection", exact: true })
      .click()
      .catch(() => {});
    await page.waitForFunction(
      () => !document.body.innerText.includes("Started from issue #1"),
      null,
      { timeout: 30000 },
    );
  } finally {
    await rm(repo, { recursive: true, force: true });
  }
  return [
    "tasks-start-from-issue-creates-worktree-with-issue-badge",
    "tasks-start-leaves-no-worktree-or-project-behind",
  ];
}

