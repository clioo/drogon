/// One entry from `tests/parity/ports/WP-CAP-BOTS/native-input/fixtures/expected.json`,
/// generated by executing the actual pinned source parser (see that
/// directory's README) -- never hand-authored expected values.
#[derive(Deserialize)]
struct Fixture {
    id: String,
    parser: String,
    input: Value,
    expect: String,
    #[serde(default)]
    output: Option<Value>,
}

#[derive(Deserialize)]
struct FixtureFile {
    fixtures: Vec<Fixture>,
}

fn dispatch(fixture: &Fixture) -> Result<Value, BotInputError> {
    match fixture.parser.as_str() {
        "botCreate" => input::parse_bot_create(&fixture.input),
        "botUpdate" => input::parse_bot_update(&fixture.input),
        "botSession" => input::parse_bot_session(&fixture.input),
        "responsibilityCreate" => input::parse_responsibility_create(&fixture.input),
        "botId" => input::parse_bot_id(&fixture.input),
        other => panic!("fixture {}: unknown parser {other}", fixture.id),
    }
}

fn load_fixtures() -> FixtureFile {
    // Embedded at compile time so this test never depends on the process's
    // cwd (never the read-only source checkout, per the migration
    // contract) -- only on this file's own fixed location in the tree.
    const RAW: &str =
        include_str!("../../../tests/parity/ports/WP-CAP-BOTS/native-input/fixtures/expected.json");
    serde_json::from_str(RAW).expect("fixtures/expected.json must be valid JSON")
}

/// Structural equality except for `Number`: two numbers compare equal by
/// numeric value (`as_f64`), not by `serde_json::Number`'s int-vs-float
/// storage kind (a JSON source has no such distinction -- `1` and `1.0`
/// are the same value, but `serde_json::Value::from(1.0_f64) != Value::from(1_u64)`
/// under plain `==`). Still an exact `f64` comparison, so a genuine value
/// difference (precision loss, a wrong magnitude) is never hidden.
fn json_numerically_eq(a: &Value, b: &Value) -> bool {
    match (a, b) {
        (Value::Number(x), Value::Number(y)) => x.as_f64() == y.as_f64(),
        (Value::Array(x), Value::Array(y)) => {
            x.len() == y.len() && x.iter().zip(y).all(|(xi, yi)| json_numerically_eq(xi, yi))
        }
        (Value::Object(x), Value::Object(y)) => {
            x.len() == y.len()
                && x.iter()
                    .all(|(k, v)| y.get(k).is_some_and(|yv| json_numerically_eq(v, yv)))
        }
        _ => a == b,
    }
}

/// The core parity gate: every bounded fixture, generated by actually
/// executing the pinned source parser (see the native-input README),
/// replayed through the native parser. An "accept" fixture requires the
/// native parser to accept *and* produce the same normalized JSON the
/// source produced (compared with `json_numerically_eq`, not raw `==` --
/// see its doc comment); a "reject" fixture requires the native parser to
/// reject too (the specific `BotInputError` category/path is not required
/// to match zod's own issue text -- only the accept/reject boundary and,
/// for accepted cases, the normalized output).
#[test]
fn fixture_battery_matches_source_parser() {
    let file = load_fixtures();
    assert!(
        file.fixtures.len() >= 140,
        "expected a substantial bounded fixture battery, got {}",
        file.fixtures.len()
    );
    let mut accepted = 0usize;
    let mut rejected = 0usize;
    for fixture in &file.fixtures {
        let result = dispatch(fixture);
        match fixture.expect.as_str() {
            "accept" => {
                accepted += 1;
                let value = result.unwrap_or_else(|error| {
                    panic!(
                        "fixture {} ({}): source accepted but native rejected: {error:?}",
                        fixture.id, fixture.parser
                    )
                });
                let expected = fixture.output.as_ref().unwrap_or_else(|| {
                    panic!("fixture {}: accept fixture missing output", fixture.id)
                });
                assert!(
                    json_numerically_eq(&value, expected),
                    "fixture {} ({}): normalized output mismatch: native={value:?} source={expected:?}",
                    fixture.id,
                    fixture.parser
                );
            }
            "reject" => {
                rejected += 1;
                assert!(
                    result.is_err(),
                    "fixture {} ({}): source rejected but native accepted: {:?}",
                    fixture.id,
                    fixture.parser,
                    result.ok()
                );
            }
            other => panic!("fixture {}: unknown expect value {other}", fixture.id),
        }
    }
    // Sanity: the battery actually exercises both boundaries, not just one.
    assert!(
        accepted > 0 && rejected > 0,
        "fixture battery must cover both accept and reject"
    );
}

