/**
 * The surfaces probe's CLI-driven automation run is a headless session in
 * this workspace; when its agent errors (e.g. the shared model server
 * answering 429) it exits into a strip stub whose overlay blocks pointer
 * events across the window. Close any exited stubs through their own tab
 * control so the journey probes interact with an unobstructed window.
 */
async function closeExitedStripTabs(page) {
  // The Sessions strip is unmounted on the Bots/Automations/Tasks routes.
  // Preserve the visible nav route, briefly use the real Sessions tab close
  // controls, then return so the caller's user journey is uninterrupted.
  const route = await page.evaluate(() => {
    const names = new Set(["Sessions", "Bots", "Tasks", "Automations"]);
    return (
      [...document.querySelectorAll('button[aria-current="page"]')]
        .map((button) => button.textContent?.trim() ?? "")
        .find((name) => names.has(name)) ?? null
    );
  });
  if (route && route !== "Sessions") {
    await page
      .getByRole("button", { name: "Sessions", exact: true })
      .first()
      .click();
    await page.getByRole("button", { name: "New tab", exact: true }).waitFor();
  }
  for (let guard = 0; guard < 5; guard += 1) {
    const exited = page.locator(
      '[role="tablist"][aria-label="Sessions"] [role="tab"][aria-label$=" exited"]',
    );
    if ((await exited.count()) === 0) break;
    const tab = exited.first();
    const closer = tab.locator('[data-tab-close-button="true"]');
    if ((await closer.count()) > 0) {
      // Inactive strip close controls are visually transparent; this is the
      // actual tab handler, so force only the pointer path through that
      // rendered control rather than dismissing the daemon record directly.
      await closer.click({ force: true });
    } else {
      await tab.click({ force: true });
      await page
        .getByRole("button", { name: "Close", exact: true })
        .first()
        .click({ force: true });
    }
    await delay(300);
  }
  if (route && route !== "Sessions") {
    await page.getByRole("button", { name: route, exact: true }).first().click();
  }
}

