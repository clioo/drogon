/** Diagnostic dump for the J1 state waits: strip tabs, live sessions and
 *  registry tails, so a failed run shows whether the tab vanished, the
 *  state never propagated, or the prompt went to another terminal. */
async function j1Diagnostics(page, workspaceId) {
  return page.evaluate(async (id) => {
    const tabs = [
      ...document.querySelectorAll(
        '[role="tablist"][aria-label="Sessions"] [role="tab"]',
      ),
    ].map((tab) => ({
      id: tab.getAttribute("data-tab-id"),
      label: tab.getAttribute("aria-label"),
      selected: tab.getAttribute("aria-selected"),
    }));
    let sessions = null;
    try {
      const response = await window.drogon.sessions(id);
      if (response.ok)
        sessions = response.result.sessions.map((session) => ({
          id: session.id,
          command: session.command,
          verdict: session.verdict,
          agentState: session.agentState,
          agentStateAt: session.agentStateAt,
        }));
    } catch {
      sessions = "sessions rpc failed";
    }
    const registry = window.__drogonTerminals;
    const terminals = registry
      ? [...registry.entries()].map(([key, terminal]) => {
          const buffer = terminal.buffer.active;
          const tail = [];
          for (let row = Math.max(0, buffer.length - 4); row < buffer.length; row += 1)
            tail.push(buffer.getLine(row)?.translateToString(true) ?? "");
          return { key, rows: buffer.length, tail };
        })
      : "no registry";
    const focused = document.activeElement?.className ?? String(document.activeElement?.tagName);
    return { tabs, sessions, terminals, focused };
  }, workspaceId);
}

