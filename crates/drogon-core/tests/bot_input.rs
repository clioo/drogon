// --- Additional bounded assertions on error shape (category/path), which
// the fixture battery deliberately does not check (see its doc comment). ---

#[test]
fn errors_carry_a_stable_category_and_field_path_without_echoing_payload_content() {
    let error = parse_bot_create(&json!({
        "characterPreset": "none",
        "displayIdentity": { "displayName": "Watcher", "handle": null, "title": null },
        "harnessPolicy": { "defaultHarness": "codex", "explicitModel": null },
        "instructions": "top secret credential leak attempt",
        "memories": [],
        "privileged": true
    }))
    .expect_err("must reject");
    assert_eq!(error.category, InvalidInputCategory::UnknownField);
    // Root review: an UnknownField path names only the enclosing object,
    // never the offending key -- see unknown_key_errors_never_echo_the_key
    // below for the dedicated privacy regression.
    assert_eq!(error.path, "");
    // Bounded privacy: the rejected instructions text never appears in the
    // error's Display output or its structured fields.
    let displayed = error.to_string();
    assert!(!displayed.contains("top secret credential leak attempt"));

    let harness_error = input::parse_bot_session(&json!({
        "sessionId": "session-1",
        "harness": "invented-harness",
        "model": null,
        "startedAt": 1
    }))
    .expect_err("must reject");
    assert_eq!(
        harness_error.category,
        InvalidInputCategory::UnsupportedHarness
    );
    assert_eq!(harness_error.path, "harness");

    let cross_field_error = input::parse_responsibility_create(&json!({
        "name": "Invalid reactive schedule",
        "instructions": "x",
        "kind": "reactive",
        "schedule": {
            "projectId": "repo-1",
            "workspaceMode": "new_per_run",
            "timezone": "UTC",
            "rrule": "FREQ=DAILY",
            "dtstart": 1
        }
    }))
    .expect_err("must reject");
    assert_eq!(
        cross_field_error.category,
        InvalidInputCategory::CrossFieldConflict
    );
    assert_eq!(cross_field_error.path, "schedule");

    let range_error = parse_bot_create(&json!({
        "characterPreset": "none",
        "displayIdentity": { "displayName": "Watcher", "handle": null, "title": null },
        "harnessPolicy": { "defaultHarness": "codex", "explicitModel": null },
        "instructions": "",
        "memories": (0..1001).map(|i| json!(format!("m{i}"))).collect::<Vec<_>>()
    }))
    .expect_err("must reject");
    assert_eq!(range_error.category, InvalidInputCategory::OutOfRange);
    assert_eq!(range_error.path, "memories");
}

/// Root review 2026-09-06 16:49 UTC: an unknown key is caller-controlled
/// input; the diagnostic path must never echo it, at any nesting depth,
/// through any of `BotInputError`'s public surfaces (`Debug`, `Display`,
/// `Serialize`).
#[test]
fn unknown_key_errors_never_echo_the_key_itself() {
    const SENSITIVE_KEY: &str = "sk-live-EXTREMELYSECRETVALUE-1234567890";

    let top_level = parse_bot_create(&json!({
        "characterPreset": "none",
        "displayIdentity": { "displayName": "Watcher", "handle": null, "title": null },
        "harnessPolicy": { "defaultHarness": "codex", "explicitModel": null },
        "instructions": "",
        "memories": [],
        SENSITIVE_KEY: "irrelevant value"
    }))
    .expect_err("must reject");
    assert_eq!(top_level.category, InvalidInputCategory::UnknownField);
    assert_eq!(top_level.path, "");

    let nested = parse_bot_create(&json!({
        "characterPreset": "none",
        "displayIdentity": { "displayName": "Watcher", "handle": null, "title": null, SENSITIVE_KEY: true },
        "harnessPolicy": { "defaultHarness": "codex", "explicitModel": null },
        "instructions": "",
        "memories": []
    }))
    .expect_err("must reject");
    assert_eq!(nested.category, InvalidInputCategory::UnknownField);
    assert_eq!(nested.path, "displayIdentity");

    for error in [&top_level, &nested] {
        assert!(!error.path.contains(SENSITIVE_KEY));
        assert!(!format!("{error:?}").contains(SENSITIVE_KEY));
        assert!(!error.to_string().contains(SENSITIVE_KEY));
        assert!(
            !serde_json::to_string(error)
                .unwrap()
                .contains(SENSITIVE_KEY)
        );
    }
}

/// Root review 2026-09-06 16:49 UTC: `str::trim` differs from ECMAScript
/// `String.prototype.trim` (Unicode `White_Space` vs. the JS `WhiteSpace`/
/// `LineTerminator` set). Fixtures generated by executing the actual
/// pinned parser (see `fixtures/expected.json`): U+FEFF is trimmed away;
/// U+0085, U+001C and U+200B are retained (none of the three is JS
/// whitespace, even though U+0085 *is* Unicode `White_Space`).
#[test]
fn trim_uses_the_ecmascript_whitespace_set_not_unicode_white_space() {
    assert_eq!(
        input::parse_bot_id(&json!("\u{feff}abc\u{feff}")).expect("must accept"),
        json!("abc")
    );
    assert_eq!(
        input::parse_bot_id(&json!("\u{85}abc\u{85}")).expect("must accept"),
        json!("\u{85}abc\u{85}")
    );
    assert_eq!(
        input::parse_bot_id(&json!("\u{1c}abc\u{1c}")).expect("must accept"),
        json!("\u{1c}abc\u{1c}")
    );
    assert_eq!(
        input::parse_bot_id(&json!("\u{200b}abc\u{200b}")).expect("must accept"),
        json!("\u{200b}abc\u{200b}")
    );
}

/// Root review 2026-09-06 16:49 UTC: a finite nonnegative timestamp must
/// round-trip exactly, with no invented "safe integer" bound and no
/// saturating cast. Values and expectations executed against the actual
/// pinned parser (see `fixtures/expected.json`'s `bot_session/timestamp_*`
/// entries); `2**64 - 2048`/`2**64`/`2**64 + 4096` are each exactly
/// representable `f64` values one ULP apart at that magnitude, and
/// `Number.MAX_VALUE` is exactly `f64::MAX`.
#[test]
fn timestamps_preserve_exact_finite_nonnegative_source_values() {
    let session = |value: f64| {
        input::parse_bot_session(&json!({
            "sessionId": "s", "harness": "codex", "model": null, "startedAt": value
        }))
        .unwrap_or_else(|error| panic!("must accept {value}: {error:?}"))
    };
    let started_at = |value: f64| {
        session(value)["startedAt"]
            .as_f64()
            .expect("startedAt must be a number")
    };
    assert_eq!(started_at(0.0), 0.0);
    assert_eq!(started_at(0.5), 0.5);
    assert_eq!(started_at(2f64.powi(64) - 2048.0), 2f64.powi(64) - 2048.0);
    assert_eq!(started_at(2f64.powi(64)), 2f64.powi(64));
    assert_eq!(started_at(2f64.powi(64) + 4096.0), 2f64.powi(64) + 4096.0);
    assert_eq!(started_at(f64::MAX), f64::MAX);

    // A reparsed f64 alone can hide a representation-level value change: a
    // saturating `2**64 as u64` cast produces `u64::MAX`, a genuinely
    // different integer, but `u64::MAX as f64` happens to round back up to
    // exactly `2**64` -- the same bit pattern, masking the defect. Check
    // the actual serialized JSON text too, which does not round-trip that
    // coincidence away: `u64::MAX` serializes as `18446744073709551615`,
    // never the source's own `1.8446744073709552e19`-shaped float text.
    let serialized = serde_json::to_string(&session(2f64.powi(64))).expect("serializable");
    assert!(
        !serialized.contains("18446744073709551615"),
        "startedAt must not silently become u64::MAX's digit string: {serialized}"
    );
}

